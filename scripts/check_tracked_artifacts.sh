#!/usr/bin/env bash
# Tracked-artifact guard (bead hearsay-four-qwz--portable-tests-hygiene, HYG-1):
# no audio binaries, model weights, or logs may be tracked, except the narrow
# data/demo fixtures. With `--strict` (CI, after the suite) it also fails on
# any dirty tree state, proving tests emit no artifacts into the repo.
# Fails red (exit 1) on any hit; green prints the verdict line.
set -u
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fail=0
hit() { echo "GUARD-RED: $1"; fail=1; }
# `--strict` (CI only, run after the test suite): the tree must be clean —
# tests are hermetic and emit no artifacts into the repo. Local runs omit
# it so work-in-progress edits are not flagged.
STRICT=0
[ "${1:-}" = "--strict" ] && STRICT=1

# Narrow exceptions: committed fixtures the suite reads (see .gitignore).
# - data/demo/sample.wav (bead 9hh zero-config demo fixture)
# - data/demo/serve-mp3.mp3 + serve-mp3-twin.wav + corrupt.mp3 (MP3-1 fixtures)
is_exception() {
  case "$1" in
    data/demo/sample.wav|data/demo/serve-mp3.mp3|data/demo/serve-mp3-twin.wav|data/demo/corrupt.mp3)
      return 0 ;;
    *) return 1 ;;
  esac
}

# 1. Tracked audio binaries outside the allowlist.
while IFS= read -r f; do
  [ -z "$f" ] && continue
  if ! is_exception "$f"; then
    hit "tracked audio binary: $f (git rm it; audio stays out of git)"
  fi
done < <(cd "$REPO" && git ls-files '*.wav' '*.mp3' '*.flac' '*.ogg' 2>/dev/null)

# 2. Tracked model weights / binaries (regenerated by training gates).
while IFS= read -r f; do
  [ -z "$f" ] && continue
  hit "tracked model/weight binary: $f (git rm it; models/ holds JSON only)"
done < <(cd "$REPO" && git ls-files '*.pt' '*.pth' '*.onnx' '*.safetensors' '*.gguf' '*.ckpt' 'models/si_base/model.bin' 2>/dev/null)

# 3. Tracked logs.
while IFS= read -r f; do
  [ -z "$f" ] && continue
  hit "tracked log file: $f (git rm it)"
done < <(cd "$REPO" && git ls-files '*.log' 2>/dev/null)

# 4. `--strict` only: post-test tree cleanliness. CI runs the suite, then
# this guard with `--strict`: any modified or untracked (non-ignored) file
# is a test-emitted artifact and fails the check.
if [ "$STRICT" -eq 1 ]; then
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    hit "dirty tree after tests: $f (tests must write to target/ or clean up)"
  done < <(cd "$REPO" && git status --porcelain 2>/dev/null)
fi

if [ "$fail" -eq 0 ]; then
  echo "ARTIFACT GUARD GREEN: no tracked audio/weights/logs outside data/demo fixtures, no untracked artifacts."
fi
exit "$fail"
